def module_href(from_dir, key):
    return os.path.relpath(mpp.target_path(key), from_dir).replace(os.sep, '/')


def build_nav(from_dir, spec):
    nav = []
    index = os.path.join(OUT_DIR, 'index.html')
    nav.append({'t': 'فهرست خطاها و آلارم‌ها', 'href': os.path.relpath(index, from_dir).replace(os.sep, '/')})
    seen = set()
    for key in spec.get('mods', ('ui',)):
        if key in seen:
            continue
        seen.add(key)
        label = dict(mpp.NAVLABELS).get(key, key)
        nav.append({'t': 'صفحهٔ ' + label, 'href': module_href(from_dir, key)})
    sim = os.path.join(ROOT, 'Firmware', 'Modules', 'Ui', 'alarm_simulator.html')
    nav.append({'t': 'شبیه‌ساز چراغ و بوق',
                'href': os.path.relpath(sim, from_dir).replace(os.sep, '/')})
    return nav


def err_map(from_dir, spec):
    out = {}
    pages = {'۰': 'fault_0_adc', '۶': 'fault_6_battery_lost', '۷': 'fault_7_technical'}
    for digit, slug in pages.items():
        if slug == spec['slug']:
            continue
        out[digit] = os.path.relpath(os.path.join(OUT_DIR, slug + '.html'), from_dir).replace(os.sep, '/')
    return out


def build_page(spec, idx):
    path = os.path.join(OUT_DIR, spec['slug'] + '.html')
    from_dir = os.path.dirname(path)
    data = {
        'file': spec['slug'] + '.html',
        'title': spec['title'],
        'sub': spec['sub'],
        'steps': spec['steps'],
        'example': spec['example'],
        'flow': spec['flow'],
        'tree': spec['tree'],
        'conds': spec['conds'],
        'outs': spec['outs'],
        'menu': mpp.build_menu(from_dir, 'alarm:' + spec['slug']),
        'errmap': err_map(from_dir, spec),
        'gloss': [list(row) for row in mpp.GLOSSARY],
    }
    fallback = GH
    for node in data['flow']:
        if node.get('ref'):
            node['rurl'] = mpp.resolve_ref(node['ref'], idx, fallback)
    data = mpp.plain_module(data)
    html = TEMPLATE.replace('__TITLE__', spec['title'])
    html = html.replace('/*__MENUCSS__*/', mpp.MENU_CSS).replace('/*__MENUJS__*/', mpp.MENU_JS)
    html = html.replace('/*__DATA__*/', json.dumps(data, ensure_ascii=False))
    with open(path, 'w', encoding='utf-8') as f:
        f.write(html)
    print('wrote', path)


