#!/usr/bin/env bash
# [EN] Host-side syntax gate for CubeIDE Core and Firmware sources.
set -euo pipefail
SCRIPT_DIRECTORY="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPOSITORY_ROOT="$(cd "${SCRIPT_DIRECTORY}/.." && pwd)"
cd "${REPOSITORY_ROOT}"
INCLUDE_FLAGS=(
    -I CubeIDE/Core/Inc
    -I CubeIDE/Drivers/CMSIS/Include
    -I CubeIDE/Drivers/CMSIS/Device/ST/STM32F1xx/Include
    -I CubeIDE/Drivers/STM32F1xx_HAL_Driver/Inc
    -I CubeIDE/Drivers/STM32F1xx_HAL_Driver/Inc/Legacy
    -I CubeIDE/Middlewares/Third_Party/FreeRTOS/Source/include
    -I CubeIDE/Middlewares/Third_Party/FreeRTOS/Source/CMSIS_RTOS_V2
    -I CubeIDE/Middlewares/Third_Party/FreeRTOS/Source/portable/GCC/ARM_CM3
    -I Firmware/App/Inc
    -I Firmware/Bsp/Inc
    -I Firmware/Config/Inc
    -I Firmware/Rtos/Inc
    -I Firmware/Modules/Ui
    -I Firmware/Modules/Measurement
    -I Firmware/Modules/Protection
    -I Firmware/Modules/Changeover
    -I Firmware/Modules/Charger
    -I Firmware/Modules/Jitter
    -I Firmware/Modules/Fault
    -I Firmware/Modules/EspLink
    -I Firmware/Modules/McuPowerPath
    -I Firmware/Modules/Imbalance
    -I Firmware/Modules/CalLut
    -I Firmware/Modules/Diag
    -I Firmware/Modules/FlashLock
)
# [EN] Tester/ holds host harnesses (fake clock, stub BSP). They are built and
#      run by their own runners further down, so they are excluded from the
#      firmware syntax sweep - otherwise their stub definitions would be read
#      as a second implementation of the real symbols.
SOURCE_FILES=(
    $(find CubeIDE/Core/Src Firmware -type f -name '*.c' -not -path '*/Tester/*' | sort)
)
# [EN] Extra warnings applied to OUR sources only (Firmware/). The vendor
#      trees under CubeIDE/ are generated by ST and trip -Wredundant-decls in
#      system_stm32f1xx.h, so they keep the base flag set. Added 2026-10-06
#      after a programmer-role pass that cleaned every finding these produce:
#      the tree is warning-free under them today, so they are a gate, not a
#      wish list.
STRICT_FLAGS=(
    -Wshadow
    -Wundef
    -Wmissing-prototypes
    -Wstrict-prototypes
    -Wredundant-decls
    -Wcast-qual
)
for SOURCE_FILE in "${SOURCE_FILES[@]}"; do
    EXTRA_FLAGS=()
    case "${SOURCE_FILE}" in
        Firmware/*) EXTRA_FLAGS=("${STRICT_FLAGS[@]}") ;;
        *)          EXTRA_FLAGS=() ;;
    esac
    gcc \
        -fsyntax-only \
        -std=c11 \
        -Wall \
        -Wextra \
        -Werror \
        -Wno-int-to-pointer-cast \
        "${EXTRA_FLAGS[@]}" \
        -DSTM32F103xB \
        -DUSE_HAL_DRIVER \
        "${INCLUDE_FLAGS[@]}" \
        "${SOURCE_FILE}"
done
# [EN] The ESP sketch is a second program in this repository and it was never
#      built by any gate: until now the only compiler that ever read it was the
#      Arduino IDE, at flashing time. It is C++, not C, so it gets its own step.
echo "--- ESP sketch (C++) / اسکچ ESP ---"
./ESP_Calibration/Tester/run_esp_tests.sh
# [EN] Module host testers (tidy-up 2026-10-05): the UI, Charger and
#      Imbalance testers existed but no gate ever ran them, so a red test
#      could sit in the tree unnoticed. They are hardware-free, take a few
#      seconds, and fail the gate like any compile error. They do NOT
#      replace the real board tests recorded in each module Excel.
echo "--- UI host tests / تست هاست UI ---"
python3 Firmware/Modules/Ui/Tester/host_test_ui.py
echo "--- Charger host tests / تست هاست شارژر ---"
python3 Firmware/Modules/Charger/Tester/host_test_charger.py
# [EN] Run deterministic scenario-6 regression checks in the panel preview simulator.
echo "--- Panel preview scenario-6 self-test / تست سناریوی ۶ شبیه‌ساز ---"
node tools/panel_preview_server.js --self-test
echo "--- Imbalance host test / تست هاست عدم‌توازن ---"
./Firmware/Modules/Imbalance/Tester/run_host_test_imbalance.sh
# [EN] Cross-module regression: the live Fault removal signal must be wired
#      through TaskControl to Imbalance, and a 3 s swap clears persisted state.
echo "--- Battery swap integration test / تست یکپارچهٔ تعویض باتری ---"
./Firmware/Modules/Imbalance/Tester/run_host_test_battery_swap.sh
echo "--- Changeover host test / تست هاست Changeover ---"
./Firmware/Modules/Changeover/Tester/run_host_test_changeover.sh
echo "--- Fault host test / تست هاست Fault ---"
./Firmware/Modules/Fault/Tester/run_host_test_fault.sh
echo "--- Protection host test / تست هاست Protection ---"
./Firmware/Modules/Protection/Tester/run_host_test_protection.sh
echo "--- Jitter host test / تست هاست Jitter ---"
./Firmware/Modules/Jitter/Tester/run_host_test_jitter.sh
echo "--- McuPowerPath host test / تست هاست McuPowerPath ---"
./Firmware/Modules/McuPowerPath/Tester/run_host_test_mcu_power_path.sh
echo "--- CalLut host test / تست هاست CalLut ---"
./Firmware/Modules/CalLut/Tester/run_host_test_cal_lut.sh
echo "--- Measurement host test / تست هاست Measurement ---"
./Firmware/Modules/Measurement/Tester/run_host_test_measurement.sh
# [EN] bsp_gpio.c is the only file that maps a logical signal to a pin and a
#      physical level, and it was the only firmware file no host test ever
#      executed: the module testers use a fake BSP. Added 2026-10-20 with the
#      JITTER1/2 polarity fix so a wrong active level turns the gate red.
echo "--- BSP GPIO polarity host test / تست هاست قطبیت GPIO برد ---"
./Firmware/Bsp/Tester/run_host_test_bsp_gpio.sh
echo "--- FlashLock host test / تست هاست قفل خواندن ---"
./Firmware/Modules/FlashLock/Tester/run_host_test_flash_lock.sh
# [EN] diag.c was the only module with no host test at all: the uptime base
#      and the "save while charging" policy could only be judged on the board.
#      Added 2026-10-28 with the audit fix; the pages are mapped at their real
#      addresses so the module is executed exactly as it runs on the chip.
echo "--- Diag host test / تست هاست دیاگ ---"
./Firmware/Modules/Diag/Tester/run_host_test_diag.sh
echo "--- EspLink NVM host test / تست هاست NVM لینک ESP ---"
./Firmware/Modules/EspLink/Tester/run_host_test_nvm.sh
echo "--- EspLink parser host test / تست هاست پارسر لینک ESP ---"
./Firmware/Modules/EspLink/Tester/run_host_test_parser.sh
echo "HOST SYNTAX CHECK PASSED / بررسی syntax سمت Host موفق بود"
